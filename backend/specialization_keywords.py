"""Production-grade medical specialization keyword dictionary.

This module is the single source of truth for mapping free-text patient
complaints (symptoms, diseases, layman wording, clinical terms, abbreviations,
spelling variants, synonym phrases) onto medical specializations.

Design principles
=================

* **Breadth.** Every specialization carries 150+ keywords/phrases spanning
  layman phrasing ("tummy ache"), clinical terminology ("epigastric pain"),
  disease names ("GERD"), abbreviations ("COPD", "UTI"), spelling variants
  ("diarhea", "diarrhoea"), and common complaint phrases ("pain while
  swallowing").

* **No surgical over-matching.** ``General Surgery`` contains ONLY genuinely
  surgical conditions (hernia, gallstones, appendicitis, abscess drainage,
  lumps requiring excision). Generic words like "fever", "pain", or "swelling"
  never appear here, which structurally eliminates the historical
  "fever -> General Surgery" misrouting.

* **Safe generalist home.** Everyday complaints (fever, cold, cough, body
  ache, fatigue) live under ``General Physician`` / ``Internal Medicine`` so
  the strict fallback is also the clinically correct destination for them.

* **Coverage of the Bangalore dataset.** Every specialty department present in
  ``blr.xlsx`` is represented: Cardiology, Dental (Dentistry), Dermatology,
  ENT, Endocrinology, Gastroenterology, General Surgery, Gynecology,
  Hematology, Nephrology, Neurology, Oncology, Ophthalmology, Orthopedics,
  Pediatrics, Plastic Surgery, Psychiatry, Pulmonology, Rheumatology, Urology
  — plus the broader triage specializations General Physician, Internal
  Medicine, Physiotherapy, and Nutrition/Dietetics.

The companion :mod:`specialization_mapper` consumes this dictionary; this file
contains no logic so it can be expanded freely without touching the matcher.
"""

